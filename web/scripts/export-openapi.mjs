// Exports the backend's OpenAPI schema and generates src/api/schema.d.ts from it.
// Usage: node scripts/export-openapi.mjs [outFile]   (default: src/api/schema.d.ts)
//
// openapi-typescript needs the TypeScript 5 compiler API (its peer range is ^5), which the
// project's TypeScript 7 does not provide, so it is run through npx with its own pinned
// TypeScript 5 instead of being a project dependency.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OPENAPI_TYPESCRIPT = "openapi-typescript@7.13.0";
const TYPESCRIPT = "typescript@5.9.3";

// Bounded so an offline first run fails instead of hanging; the staleness test allows a bit longer.
const NPX_TIMEOUT_MS = Number(process.env.NETPULSE_NPX_TIMEOUT_MS) || 90_000;

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const backendDir = path.resolve(webDir, "..", "backend");

export function backendPython() {
  const rel = process.platform === "win32" ? ["Scripts", "python.exe"] : ["bin", "python"];
  return path.join(backendDir, ".venv", ...rel);
}

// How to start npx without a shell: its JS entry run by this node, or plain `npx` on POSIX.
function npxCommand() {
  if (process.platform !== "win32") return ["npx", []];
  const npmCli = process.env.npm_execpath;
  const fromNpm = npmCli && path.join(path.dirname(npmCli), "npx-cli.js");
  const bundled = path.join(path.dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js");
  const entry = [fromNpm, bundled].find((p) => p && existsSync(p));
  if (!entry) throw new Error("could not find npx-cli.js next to npm or node");
  return [process.execPath, [entry]];
}

export function generateSchema() {
  const python = backendPython();
  if (!existsSync(python)) throw new Error(`backend venv python not found: ${python}`);
  const tmp = mkdtempSync(path.join(tmpdir(), "netpulse-openapi-"));
  try {
    const spec = path.join(tmp, "openapi.json");
    const generated = path.join(tmp, "schema.d.ts");
    const json = execFileSync(
      python,
      ["-c", "import json,sys; from app.main import create_app; json.dump(create_app().openapi(), sys.stdout)"],
      // The app factory is only asked for its schema, but keep any data folder out of the repo.
      { cwd: backendDir, env: { ...process.env, NETPULSE_DATA_DIR: path.join(tmp, "data") }, maxBuffer: 64 * 1024 * 1024 },
    );
    writeFileSync(spec, json);
    const [cmd, cmdArgs] = npxCommand();
    try {
      execFileSync(
        cmd,
        [...cmdArgs, "--yes", "-p", TYPESCRIPT, "-p", OPENAPI_TYPESCRIPT, "openapi-typescript", "openapi.json", "-o", "schema.d.ts", "--default-non-nullable", "false"],
        // Relative names plus cwd: tmp keep every argument free of spaces. No shell, so the timeout kills the real process.
        { cwd: tmp, stdio: ["ignore", "pipe", "pipe"], timeout: NPX_TIMEOUT_MS },
      );
    } catch (e) {
      if (e.code === "ETIMEDOUT") throw new Error(`npx timed out after ${NPX_TIMEOUT_MS / 1000} s`);
      const line = String(e.stderr ?? "").split("\n").find((l) => l.trim());
      throw new Error(line?.trim() ?? e.message);
    }
    return `// Generated by \`npm run gen:api\` from the backend OpenAPI schema. Do not edit.\n${readFileSync(generated, "utf8")}`;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const out = path.resolve(process.argv[2] ?? path.join(webDir, "src", "api", "schema.d.ts"));
    const schema = generateSchema();
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, schema);
    console.log(`wrote ${out}`);
  } catch (e) {
    console.error(`gen:api failed: ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  }
}
