// Exports the backend's OpenAPI schema and generates src/api/schema.d.ts from it.
// Usage: node scripts/export-openapi.mjs [outFile]   (default: src/api/schema.d.ts)
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { register } from "node:module";

// openapi-typescript drives the TypeScript compiler API, which TypeScript 7 (native) does not
// provide. Redirect its `typescript` import to the TypeScript 5 copy installed as `typescript5`.
const ts5 = new URL(import.meta.resolve("typescript5")).href;
register(
  "data:text/javascript," +
    encodeURIComponent(
      `export async function resolve(s, c, next) {
         if (s === "typescript" && c.parentURL?.includes("/node_modules/openapi-typescript/"))
           return { url: ${JSON.stringify(ts5)}, shortCircuit: true };
         return next(s, c);
       }`,
    ),
);
const { default: openapiTS, astToString } = await import("openapi-typescript");

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const backendDir = path.resolve(webDir, "..", "backend");

export function backendPython() {
  const rel = process.platform === "win32" ? ["Scripts", "python.exe"] : ["bin", "python"];
  return path.join(backendDir, ".venv", ...rel);
}

export async function generateSchema() {
  const python = backendPython();
  if (!existsSync(python)) throw new Error(`backend venv python not found: ${python}`);
  const dataDir = mkdtempSync(path.join(tmpdir(), "netpulse-openapi-"));
  try {
    const json = execFileSync(
      python,
      ["-c", "import json,sys; from app.main import create_app; json.dump(create_app().openapi(), sys.stdout)"],
      { cwd: backendDir, env: { ...process.env, NETPULSE_DATA_DIR: dataDir }, maxBuffer: 64 * 1024 * 1024 },
    ).toString("utf8");
    writeFileSync(path.join(dataDir, "openapi.json"), json);
    const ast = await openapiTS(JSON.parse(json), { defaultNonNullable: false });
    return `// Generated by \`npm run gen:api\` from the backend OpenAPI schema. Do not edit.\n${astToString(ast)}`;
  } finally {
    rmSync(dataDir, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.resolve(process.argv[2] ?? path.join(webDir, "src", "api", "schema.d.ts"));
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, await generateSchema());
  console.log(`wrote ${out}`);
}
